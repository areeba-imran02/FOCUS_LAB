from focuslab_core.fallback import classify_error, local_fallback_plan
from focuslab_core.gemini_client import generate_plan

def test_error_classification():
    assert classify_error(RuntimeError('HTTP 429 quota'))=='quota'
    assert classify_error(RuntimeError('401 invalid API key'))=='auth'
    assert classify_error(TimeoutError('request timeout'))=='timeout'
    assert classify_error(RuntimeError('503 temporarily unavailable'))=='temporary'

def test_local_fallback_and_missing_key(monkeypatch):
    monkeypatch.setattr('focuslab_core.gemini_client.get_api_key',lambda:'')
    intake={'task':'Study SQL','available_minutes':30,'problem':'phone','distractions':['messaging']}
    plan,status,attempts=generate_plan(intake,consent=True)
    assert plan.source=='local' and 'configuration required' in status.lower() and attempts==[]
    assert sum(s.minutes for s in plan.steps)<=30

def test_fallback_plan_is_explicit():
    plan=local_fallback_plan({'task':'Read','available_minutes':20})
    assert 'not generated by Gemini' in plan['summary']
    assert plan['source']=='local'


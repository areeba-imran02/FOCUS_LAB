def test_generation_attempts_are_bounded(monkeypatch):
    import sys, types
    from focuslab_core import gemini_client
    calls=[]
    class Models:
        def list(self, config=None): return []
        def generate_content(self, **kwargs):
            calls.append(kwargs['model'])
            raise RuntimeError('503 temporarily unavailable')
    class Client:
        def __init__(self, **kwargs): self.models=Models()
    genai_mod=types.ModuleType('google.genai'); genai_mod.Client=Client
    types_mod=types.ModuleType('google.genai.types')
    class HttpOptions:
        def __init__(self, **kwargs): pass
    types_mod.HttpOptions=HttpOptions
    google_mod=types.ModuleType('google'); google_mod.__path__=[]
    monkeypatch.setitem(sys.modules,'google',google_mod)
    monkeypatch.setitem(sys.modules,'google.genai',genai_mod)
    monkeypatch.setitem(sys.modules,'google.genai.types',types_mod)
    monkeypatch.setattr(gemini_client,'get_api_key',lambda:'test-key')
    plan,status,attempts=gemini_client.generate_plan({'task':'Study','available_minutes':30},consent=True,max_attempts=2)
    assert plan.source=='local'
    assert len(calls)==2 and len(attempts)==2

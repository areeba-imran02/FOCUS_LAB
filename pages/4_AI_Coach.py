import streamlit as st
from focuslab_core.coach import run_focus_coach
from focuslab_core.evidence import retrieve_evidence

st.set_page_config(page_title="Focus coach · FocusLab",page_icon="✨",layout="wide")
st.title("04 · Focus coach")
intake=st.session_state.get("intake",{"problem":"","task":"","available_minutes":30,"distractions":[],"constraints":"","language":"English"})
st.write("A bounded coach combines your approved intake, deterministic experiment metrics, and local evidence passages. Local fallback remains available without credentials.")
st.warning("If you opt in, the intake, experiment summary, and retrieved research snippets are sent to Google's Gemini API. Do not include confidential or identifying information. Your experiment scoring itself remains local.")
consent=st.checkbox("I consent to sending the information described above to Gemini to generate a plan.",value=False)
if st.button("Generate my plan",type="primary"):
    with st.spinner("Preparing a plan…"):
        result=run_focus_coach(intake,st.session_state.get("experiment_metrics",{}),consent=consent)
    st.session_state.coach_result={"plan":result["plan"].model_dump(),"status":result["status"],"attempts":result["attempts"],"evidence":result["evidence"],"tools_used":result["tools_used"]}
result=st.session_state.get("coach_result")
if result:
    plan=result["plan"]; st.info(result["status"]); st.markdown(f"### {plan['summary']}")
    for i,step in enumerate(plan["steps"],1): st.markdown(f"<div class='fl-card'><b>{i}. {step['title']}</b><span style='float:right'>{step['minutes']} min</span><p>{step['rationale']}</p></div>",unsafe_allow_html=True)
    st.markdown("### Environment changes")
    for x in plan["environment_changes"]: st.checkbox(x,key="coach_"+x)
    st.markdown("### If interrupted")
    st.write(plan["if_interrupted"])
    st.caption("Plan source: Gemini" if plan["source"]=="gemini" else "Plan source: local fallback (not generated by Gemini).")
    st.caption("Tools used: "+", ".join(result["tools_used"]))
    if result["attempts"]: st.json(result["attempts"])
    st.markdown("### Retrieved local evidence")
    if result["evidence"]:
        for e in result["evidence"]: st.markdown(f"**[{e['id']}] {e['title']}**  \n{e['summary']}  \n[Open source]({e['sourceUrl']})  \n*Limitations: {e['limitations']}*")
    else: st.caption("No lexical matches for this intake; recommendations are not presented as evidence-backed.")
    if st.button("Start a focus session →",type="primary"): st.switch_page("pages/5_Focus_Session.py")
else:
    st.markdown("### Local evidence preview")
    for e in retrieve_evidence("task switching interruption notification break goal setting",k=3): st.markdown(f"**[{e['id']}] {e['title']}** — {e['summary']} ([source]({e['sourceUrl']}))")
